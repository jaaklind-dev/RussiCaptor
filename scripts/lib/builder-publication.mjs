import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export const PUBLISHED_ROOT = "assets/builder/published";
export const PUBLISHED_INDEX = `${PUBLISHED_ROOT}/index.json`;
export const COMPILED_MANIFEST = "assets/builder/compiled-packages.json";
export const COMPILED_REGISTRY = "src/services/builder/BuilderCompiledPackages.generated.ts";

export function sha256(bytes) { return crypto.createHash("sha256").update(bytes).digest("hex"); }
export function identityPath(root, packageId, version) {
  if (!/^russicaptor\.[a-z0-9][a-z0-9.-]*$/.test(packageId) || packageId.includes("..") ||
    !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version) || version.includes("..")) {
    throw new Error("BUILDER_PUBLISH_IDENTITY_INVALID");
  }
  return path.join(root, PUBLISHED_ROOT, packageId, version);
}
export function renderBuilderRegistry(packages) {
  return ["/* Generated by scripts/builder-compile.mjs. Do not edit by hand. */",
    'import type { ExercisePackage } from "@/models/exercise/ExercisePackage";',
    'import type { PackagePatientDataset } from "@/models/exercise/PackagePatientDataset";',
    `export const GENERATED_BUILDER_PACKAGES = ${JSON.stringify(packages.map(item => item.exercisePackage))} as unknown as readonly ExercisePackage[];`,
    `export const GENERATED_BUILDER_DATASETS = ${JSON.stringify(packages.map(item => item.patientDataset))} as unknown as readonly PackagePatientDataset[];`, ""].join("\n");
}
export function readCompiled(root) {
  const file = path.join(root, COMPILED_MANIFEST);
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : { schemaVersion: 1, packages: [] };
}
export function listPublications(root) {
  const directory = path.join(root, PUBLISHED_ROOT);
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).filter(item => item.isDirectory()).flatMap(item => {
    const parent = path.join(directory, item.name);
    return fs.readdirSync(parent, { withFileTypes: true }).filter(version => version.isDirectory())
      .map(version => path.join(parent, version.name));
  }).sort();
}
