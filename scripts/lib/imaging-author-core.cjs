const fs = require("node:fs");
const path = require("node:path");
const ingestCore = require("./imaging-asset-ingest-core.cjs");

const AUTHORING_MANIFEST_RELATIVE_PATH = "assets/imaging/package-authoring-manifest.json";
const GENERATED_PACKAGES_RELATIVE_PATH = "src/services/imaging/ImagingAuthoredPackageVersions.generated.ts";
const IMAGE_MODALITIES = new Set(["XR", "CT", "US", "ECG", "OTHER"]);

function fail(code) { throw new Error(code); }
function semver(value, code) {
  const match = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/.exec(value ?? "");
  if (!match) fail(code);
  return { parts: match.slice(1, 4).map(Number), prerelease: match[4] };
}
function compareVersions(left, right) {
  const a = semver(left, "INVALID_BASE_VERSION"); const b = semver(right, "INVALID_NEW_VERSION");
  for (let index = 0; index < 3; index += 1) if (a.parts[index] !== b.parts[index]) return a.parts[index] - b.parts[index];
  if (a.prerelease === b.prerelease) return 0;
  if (!a.prerelease) return 1;
  if (!b.prerelease) return -1;
  return a.prerelease.localeCompare(b.prerelease);
}
function readJson(filePath, fallback) {
  if (!fs.existsSync(filePath)) return structuredClone(fallback);
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}
function readAuthoringManifest(rootDir) {
  const value = readJson(path.join(rootDir, AUTHORING_MANIFEST_RELATIVE_PATH), { schemaVersion: 1, packages: [] });
  if (value.schemaVersion !== 1 || !Array.isArray(value.packages)) fail("INVALID_IMAGING_AUTHORING_MANIFEST");
  return value;
}
function stableAuthoringManifest(manifest) {
  return { schemaVersion: 1, packages: [...manifest.packages].sort((a, b) =>
    a.packageId.localeCompare(b.packageId) || a.newVersion.localeCompare(b.newVersion)) };
}
function generatePackagesSource(manifest) {
  const lines = ["/* Generated by scripts/imaging-author.mjs. Do not edit by hand. */",
    'import type { ImagingAuthoredPackageRecipe } from "./ImagingAuthoredPackageLoader";',
    'import { deepFreeze } from "@/utils/immutable";', "",
    "export const GENERATED_IMAGING_AUTHORED_PACKAGE_RECIPES = deepFreeze(["];
  for (const recipe of stableAuthoringManifest(manifest).packages) {
    lines.push("  {", ...["packageId", "baseVersion", "basePackageHash", "newVersion", "patientId",
      "definitionId", "assetId", "expectedPackageHash"].map(key => `    ${key}: ${JSON.stringify(recipe[key])},`), "  },");
  }
  lines.push("] satisfies readonly ImagingAuthoredPackageRecipe[]);", "");
  return lines.join("\n");
}
function packageInput(base, recipe, asset, context) {
  return context.createImagingAuthoredPackage(base, recipe, asset);
}
function validateTarget(context, input) {
  semver(input.baseVersion, "INVALID_BASE_VERSION"); semver(input.newVersion, "INVALID_NEW_VERSION");
  if (compareVersions(input.newVersion, input.baseVersion) <= 0) fail("NEW_PACKAGE_VERSION_MUST_FOLLOW_BASE");
  const base = context.registry.get(input.packageId, input.baseVersion);
  if (!base) fail("IMAGING_AUTHOR_BASE_PACKAGE_NOT_FOUND");
  context.validator.assertValid(base);
  if (context.registry.get(input.packageId, input.newVersion)) fail("IMAGING_AUTHOR_NEW_VERSION_EXISTS");
  const dataset = context.datasets.resolve(base.patientDatasetId);
  if (!dataset.patients.some(item => item.patient.id === input.patientId)) fail("IMAGING_AUTHOR_PATIENT_NOT_IN_PACKAGE");
  const imaging = base.imagingConfiguration;
  if (!imaging) fail("IMAGING_AUTHOR_PACKAGE_HAS_NO_IMAGING");
  const byId = imaging.definitions.filter(item => item.study.id === input.definitionId);
  if (byId.length !== 1) fail("IMAGING_AUTHOR_DEFINITION_NOT_FOUND");
  const definition = byId[0];
  if (definition.study.patientId !== input.patientId) fail("IMAGING_AUTHOR_DEFINITION_PATIENT_MISMATCH");
  if (!IMAGE_MODALITIES.has(definition.study.modality)) fail("IMAGING_AUTHOR_UNSUPPORTED_MODALITY");
  return { base, definition };
}
function planAuthoring(rootDir, input, context) {
  const { base, definition } = validateTarget(context, input);
  const authoringManifest = readAuthoringManifest(rootDir);
  if (authoringManifest.packages.some(item => item.packageId === input.packageId && item.newVersion === input.newVersion)) {
    fail("IMAGING_AUTHOR_NEW_VERSION_EXISTS");
  }
  const assetPlan = ingestCore.planIngest(rootDir, { ...input, packageVersion: input.newVersion,
    assetVersion: input.assetVersion ?? 1, role: input.role ?? "PRIMARY_DIAGNOSTIC_IMAGE" });
  if (definition.study.asset?.assetId === assetPlan.asset.assetId) {
    fail("IMAGING_AUTHOR_REPLACEMENT_REQUIRES_NEW_ASSET_IDENTITY");
  }
  const recipeWithoutHash = { packageId: input.packageId, baseVersion: input.baseVersion,
    basePackageHash: base.packageHash, newVersion: input.newVersion, patientId: input.patientId,
    definitionId: input.definitionId, assetId: assetPlan.asset.assetId, expectedPackageHash: "" };
  const authoredWithoutExpectedHash = packageInput(base, recipeWithoutHash, assetPlan.asset, context);
  const recipe = { ...recipeWithoutHash, expectedPackageHash: authoredWithoutExpectedHash.packageHash };
  const authored = packageInput(base, recipe, assetPlan.asset, context);
  const nextAuthoringManifest = stableAuthoringManifest({ schemaVersion: 1,
    packages: [...authoringManifest.packages, recipe] });
  const files = [path.relative(rootDir, assetPlan.destinationPath), ingestCore.MANIFEST_RELATIVE_PATH,
    ingestCore.REGISTRY_RELATIVE_PATH, AUTHORING_MANIFEST_RELATIVE_PATH, GENERATED_PACKAGES_RELATIVE_PATH];
  return { operation: definition.study.asset ? "REPLACE" : "ADD", base, definition, assetPlan, recipe,
    authored, authoringManifest: nextAuthoringManifest, generatedPackagesSource: generatePackagesSource(nextAuthoringManifest),
    files, existingAssetId: definition.study.asset?.assetId };
}
function writeAtomic(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const temporary = `${filePath}.tmp-${process.pid}`;
  fs.writeFileSync(temporary, content); fs.renameSync(temporary, filePath);
}
function snapshot(filePath) {
  return fs.existsSync(filePath) ? { exists: true, bytes: fs.readFileSync(filePath) } : { exists: false };
}
function restore(filePath, state) {
  if (state.exists) { fs.mkdirSync(path.dirname(filePath), { recursive: true }); fs.writeFileSync(filePath, state.bytes); }
  else if (fs.existsSync(filePath)) fs.unlinkSync(filePath);
}
function pruneEmptyParents(start, stop) {
  for (let current = path.dirname(start); current.startsWith(stop) && current !== stop;) {
    if (!fs.existsSync(current) || fs.readdirSync(current).length) break;
    fs.rmdirSync(current); current = path.dirname(current);
  }
}
function resultFromPlan(plan, dryRun) {
  const provenance = plan.assetPlan.asset.provenance;
  return { status: dryRun ? "DRY_RUN" : "AUTHORED", operation: plan.operation,
    packageId: plan.recipe.packageId, baseVersion: plan.recipe.baseVersion, newVersion: plan.recipe.newVersion,
    patientId: plan.recipe.patientId, definitionId: plan.recipe.definitionId,
    studyHadAsset: Boolean(plan.existingAssetId), ...(plan.existingAssetId ? { previousAssetId: plan.existingAssetId } : {}),
    assetId: plan.assetPlan.asset.assetId, resolverKey: plan.assetPlan.asset.resolverKey,
    sha256: plan.assetPlan.asset.sha256, byteLength: plan.assetPlan.asset.byteLength,
    width: plan.assetPlan.asset.width, height: plan.assetPlan.asset.height,
    mediaType: plan.assetPlan.asset.mediaType, packageHash: plan.authored.packageHash,
    provenancePresent: Boolean(provenance), licenseMetadataPresent: Boolean(provenance?.licenseId || provenance?.licenseUrl),
    files: plan.files };
}
function authorPackage(rootDir, input, context, options = {}) {
  const plan = planAuthoring(rootDir, input, context);
  options.onValidated?.(resultFromPlan(plan, true));
  if (options.dryRun) return resultFromPlan(plan, true);
  const fixedPaths = [ingestCore.MANIFEST_RELATIVE_PATH, ingestCore.REGISTRY_RELATIVE_PATH,
    AUTHORING_MANIFEST_RELATIVE_PATH, GENERATED_PACKAGES_RELATIVE_PATH].map(item => path.join(rootDir, item));
  const snapshots = new Map(fixedPaths.map(file => [file, snapshot(file)]));
  const assetExisted = fs.existsSync(plan.assetPlan.destinationPath);
  try {
    const ingested = ingestCore.ingest(rootDir, { ...input, packageVersion: input.newVersion,
      assetVersion: input.assetVersion ?? 1, role: input.role ?? "PRIMARY_DIAGNOSTIC_IMAGE" });
    if (ingested.asset.assetId !== plan.recipe.assetId) fail("IMAGING_AUTHOR_INGEST_PLAN_DRIFT");
    options.afterIngest?.();
    writeAtomic(path.join(rootDir, AUTHORING_MANIFEST_RELATIVE_PATH),
      `${JSON.stringify(plan.authoringManifest, null, 2)}\n`);
    writeAtomic(path.join(rootDir, GENERATED_PACKAGES_RELATIVE_PATH), plan.generatedPackagesSource);
    ingestCore.verifyManifest(rootDir);
    if (generatePackagesSource(readAuthoringManifest(rootDir)) !== plan.generatedPackagesSource) {
      fail("IMAGING_AUTHOR_GENERATED_PACKAGE_REGISTRY_STALE");
    }
    options.validateAfterWrite?.(plan.authored);
    return resultFromPlan(plan, false);
  } catch (error) {
    for (const [file, state] of snapshots) restore(file, state);
    if (!assetExisted && fs.existsSync(plan.assetPlan.destinationPath)) fs.unlinkSync(plan.assetPlan.destinationPath);
    pruneEmptyParents(plan.assetPlan.destinationPath, path.join(rootDir, "assets/imaging"));
    throw error;
  }
}

module.exports = { AUTHORING_MANIFEST_RELATIVE_PATH, GENERATED_PACKAGES_RELATIVE_PATH, authorPackage,
  generatePackagesSource, planAuthoring, readAuthoringManifest };
